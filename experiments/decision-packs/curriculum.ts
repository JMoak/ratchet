import type { PackId, PackInput } from "../../examples/decision-packs/packs.ts";

export interface Case {
  readonly id: string;
  readonly pack: PackId;
  readonly family: string;
  readonly split: "fit" | "evaluation" | "challenge";
  readonly input: PackInput;
  readonly supported: boolean;
  readonly rationale: string;
}

function pair(
  pack: PackId,
  family: string,
  split: Case["split"],
  evidence: string,
  supported: string,
  unsupported: string,
  rationale: string,
  flags: Partial<Pick<PackInput, "sourceVerified" | "numericChecksPass" | "draftOnly">> = {},
): Case[] {
  const input = {
    sourceVerified: true,
    numericChecksPass: true,
    draftOnly: true,
    policy:
      "Assess support for a draft evidence annotation only. Preserve uncertainty; do not authorize an external action.",
    evidence,
    ...flags,
  };
  return [
    {
      id: `${pack}/${family}/a`,
      pack,
      family: `${pack}/${family}`,
      split,
      input: { ...input, candidate: supported },
      supported: true,
      rationale: `The claim preserves the source's stated scope and uncertainty. ${rationale}`,
    },
    {
      id: `${pack}/${family}/b`,
      pack,
      family: `${pack}/${family}`,
      split,
      input: { ...input, candidate: unsupported },
      supported: false,
      rationale,
    },
  ];
}

